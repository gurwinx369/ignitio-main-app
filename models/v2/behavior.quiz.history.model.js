// BehaviorQuizHistory model — completely separate from KyleHistory.
// Purpose: statistically distinguish "knows it" from "guessed it" per concept,
// via the LLR/speed-bucket formula. Triggered every 3 concepts completed,
// NOT tied to dayNumber/levelId progression at all.
//
// One document per user. Created lazily on first behavior-quiz trigger.

import mongoose, { Schema } from "mongoose";

//One graded item within a behavior-quiz session
export const BehaviorQuizAttemptSchema = new Schema(
  {
    concept: { type: String, required: true },
    difficultyTier: {
      type: String,
      enum: ["easy", "medium", "hard"],
      required: true,
    },
    question: { type: String, required: true },
    selectedOption: { type: String, required: true },
    wasCorrect: { type: Boolean, required: true },
    nOptions: { type: Number, required: true }, // per-item, not assumed global (3 now, may vary later)

    responseTimeMs: { type: Number, required: true },
    speedBucket: {
      type: String,
      enum: ["FAST", "MEDIUM", "SLOW", "GRACE", "UNATTEMPTED"],
      required: true,
    },

    llrContribution: { type: Number, required: true }, // log-odds this single item contributed
    rgbFlag: { type: Boolean, default: false }, // hard floor: t_i < max(3000ms, 0.10 * E_i)

    modelVersion: { type: String, required: true }, // likelihood-table version active at grading time
    submittedAt: { type: Date, default: Date.now },
  },
  { _id: false },
);

// Snapshot of one generated quiz item, stored in the session shell at trigger time.
// The submit route reads these back to enrich the FastAPI grading payload —
// client only sends concept + selectedOption + responseTimeMs.
const GeneratedQuizItemSchema = new Schema(
  {
    concept: { type: String, required: true },
    difficultyTier: { type: String, enum: ["easy", "medium", "hard"], required: true },
    question: { type: String, required: true },
    options: { type: [String], required: true },
    correctOption: { type: String, required: true },
    nOptions: { type: Number, required: true },
    eiSnapshot: { type: Number, required: true },
    modelVersion: { type: String, required: true },
  },
  { _id: false },
);

//One triggered behavior-quiz session (fires every 3 concepts)
const BehaviorQuizSessionSchema = new Schema(
  {
    // NEW: generated by FastAPI at /behavior/session/create, so the later
    // /behavior/session/grade call and this persisted record can be tied
    // together unambiguously. Optional so nothing else breaks if absent.
    sessionId: { type: String, index: true },

    triggeredAfterConceptCount: { type: Number, required: true }, // counter value at trigger time, for audit
    targetConcepts: { type: [String], required: true }, // concepts this session was chosen to test
    status: {
      type: String,
      enum: ["in_progress", "completed", "abandoned"],
      default: "in_progress",
    },
    // generated quiz items stored at trigger time — submit route reads these
    // to build the FastAPI grading payload without relying on client data
    generatedItems: { type: [GeneratedQuizItemSchema], default: [] },
    attempts: { type: [BehaviorQuizAttemptSchema], default: [] },
    createdAt: { type: Date, default: Date.now },
    completedAt: { type: Date, default: null },
  },
  { _id: false },
);

// Per-concept running verdict, recomputed after each completed session
const ConceptMasteryEntrySchema = new Schema(
  {
    llr_total: { type: Number, default: 0 },
    nAttempts: { type: Number, default: 0 },
    verdict: {
      type: String,
      enum: [
        "INSUFFICIENT_DATA",
        "MASTERY",
        "KNOWLEDGE_GAP",
        "DISENGAGED_GUESSING",
        "DEVELOPING",
      ],
      default: "INSUFFICIENT_DATA",
    },
    // posterior probability of mastery — trigger route reads this as priorAccuracyRate
    // so difficulty selection improves with each completed session
    posterior: { type: Number, default: null },
    modelVersion: { type: String, required: true },
    lastUpdatedAt: { type: Date, default: Date.now },
  },
  { _id: false },
);

const BehaviorQuizHistorySchema = new Schema(
  {
    firebaseUID: { type: String, required: true, unique: true, index: true },

    // Incremented once per concept completion, regardless of which concept.
    // Trigger fires when this hits a multiple of 3. Never reset to 0 — it's
    // a lifetime counter, so "every 3 concepts" keeps firing indefinitely.
    conceptsCompletedCounter: { type: Number, default: 0 },

    // Rolling log of the last 30 concepts completed, newest first.
    // Used by recordConceptCompletion to always backfill 3 targetConcepts
    // even before conceptMastery is populated (which only happens post-grading).
    recentConcepts: { type: [String], default: [] },

    // E_i anchors at (concept, difficultyTier) since items are generated
    // per-user, not drawn from a shared bank — a per-question median would
    // never get enough samples to mean anything.
    // Keyed as "concept::difficultyTier" -> shrunk expected-time estimate.
    expectedTimeAnchors: { type: Map, of: Number, default: {} },
    expectedTimeSampleCounts: { type: Map, of: Number, default: {} }, // n observed, for the empirical-Bayes shrink

    behaviorQuizSessions: { type: [BehaviorQuizSessionSchema], default: [] },

    // Keyed by concept string -> running verdict. This is what Kyle's
    // remediation logic reads from directly.
    conceptMastery: { type: Map, of: ConceptMasteryEntrySchema, default: {} },
  },
  { timestamps: true },
);

BehaviorQuizHistorySchema.index({
  firebaseUID: 1,
  "behaviorQuizSessions.status": 1,
});

// Atomic counter increment + trigger check.
// $inc is safe under concurrent concept completions — no fetch-then-save race.
BehaviorQuizHistorySchema.statics.recordConceptCompletion = async function (
  firebaseUID,
  concept,
) {
  // Prepend the new concept and cap the rolling log at 30 entries.
  // $slice on $push keeps this O(1) — no full doc read needed.
  const doc = await this.findOneAndUpdate(
    { firebaseUID },
    {
      $inc: { conceptsCompletedCounter: 1 },
      $push: { recentConcepts: { $each: [concept], $position: 0, $slice: 30 } },
      $setOnInsert: { firebaseUID },
    },
    { upsert: true, new: true },
  );

  const fired = doc.conceptsCompletedCounter % 3 === 0;
  if (!fired) return { fired: false };

  // --- Build targetConcepts (always exactly up to 3) ---
  //
  // Priority 1: concepts in conceptMastery that still need more attempts (nAttempts < 3),
  //             oldest first — so the user revisits weak spots before new ones.
  // Priority 2: fill remaining slots from recentConcepts (de-duped, skipping any already
  //             included). This is the key fix: recentConcepts is always populated
  //             (updated every call), whereas conceptMastery starts empty and is only
  //             written after a quiz is graded.

  const belowThreshold = [...doc.conceptMastery.entries()]
    .filter(([, entry]) => entry.nAttempts < 3)
    .sort((a, b) => a[1].lastUpdatedAt - b[1].lastUpdatedAt)
    .map(([conceptName]) => conceptName);

  const selected = new Set(belowThreshold.slice(0, 3));

  // Backfill from recent history until we have 3 unique concepts
  for (const c of doc.recentConcepts) {
    if (selected.size >= 3) break;
    selected.add(c);
  }

  // Final safety net: if history is so short we still can't fill 3, use current concept
  if (selected.size === 0) selected.add(concept);

  return { fired: true, targetConcepts: [...selected] };
};

export const BehaviorQuizHistory =
  mongoose.models.BehaviorQuizHistory ||
  mongoose.model("BehaviorQuizHistory", BehaviorQuizHistorySchema);
